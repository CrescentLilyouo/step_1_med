for (const chapter of physiologyChapters) {
  const topicDetails = physiologyDeepReading[chapter.id];
  if (!topicDetails) continue;
  for (const topic of chapter.topics) {
    const detail = topicDetails[topic.id];
    if (!detail) continue;

    const sections = detail.sections.map((section, index) => ({
      id: 'phys-depth-' + chapter.id + '-' + topic.id + '-' + (index + 1),
      ...section,
    }));
    const body = sections.map(section => '<section aria-labelledby="' + section.id + '"><h3 id="' + section.id
      + '" tabindex="-1">' + section.title + '</h3>' + section.body + '</section>').join('')
      + '<p class="quiz-note">延伸閱讀對照 · Guyton and Hall 第 14 版第 ' + detail.reference + ' 章。</p>';

    const questionSection = '<section><h3>用既有原題檢查本節</h3>';
    const buttons = sections.map(section => '<button type="button" data-phys-section="' + section.id + '">'
      + section.title + '</button>').join('');
    topic.html = topic.html.replace('</nav>', buttons + '</nav>');
    topic.html = topic.html.includes(questionSection)
      ? topic.html.replace(questionSection, body + questionSection)
      : topic.html + body;

    const reading = physiologyTextbooks[chapter.id].find(section => section.topic === topic.id);
    reading.html += body;
  }
}
